#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENTRY_FILE="${SCRIPT_DIR}/cli/catalog.cmake"
UTIL_FILE="${SCRIPT_DIR}/cli/internal/util.cmake"

VERSION=""
OUTPUT_FILE=""

while [[ $# -gt 0 ]]; do
  case "$1" in
    --version)
      [[ $# -ge 2 ]] || { echo "Error: --version needs a value" >&2; exit 1; }
      VERSION="$2"
      shift 2
      ;;
    -h|--help)
      echo "Usage: $0 [--version STRING] [OUTPUT_FILE]"
      echo "  OUTPUT_FILE defaults to dist/catalog"
      echo "  --version    version string shown by \`catalog version\`"
      echo "               (default: the version in cli/internal/util.cmake, plus +<git sha>)"
      exit 0
      ;;
    -*)
      echo "Error: Unknown option $1" >&2
      exit 1
      ;;
    *)
      if [[ -z "${OUTPUT_FILE}" ]]; then
        OUTPUT_FILE="$1"
        shift
      else
        echo "Error: Unexpected argument $1" >&2
        exit 1
      fi
      ;;
  esac
done

OUTPUT_FILE="${OUTPUT_FILE:-"${SCRIPT_DIR}/dist/catalog"}"
mkdir -p "$(dirname "${OUTPUT_FILE}")"

if [[ -z "${VERSION}" ]]; then
  VERSION="$(sed -nE 's/^set\(CL_VERSION "([^"]*)"\).*/\1/p' "${UTIL_FILE}")"
  if SHA="$(git -C "${SCRIPT_DIR}" rev-parse --short HEAD 2>/dev/null)"; then
    VERSION="${VERSION}+${SHA}"
  fi
fi
if [[ ! "${VERSION}" =~ ^[0-9A-Za-z.+_-]+$ ]]; then
  echo "Error: invalid version '${VERSION}'" >&2
  exit 1
fi

WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

"${SCRIPT_DIR}/bundle.sh" --minify "${WORK}/core.cmake" >/dev/null

bundle_cli() {
  local line rel_path target_file
  while IFS= read -r line || [[ -n "${line}" ]]; do
    if [[ "${line}" == "# --- bundle:core ---" ]]; then
      echo "# --- Begin: Catalog library (cmake/catalog.cmake, minified) ---"
      echo 'get_filename_component(CL_CORE_FILE "${CMAKE_CURRENT_LIST_FILE}" ABSOLUTE)'
      cat "${WORK}/core.cmake"
      echo ""
      echo "# --- End: Catalog library ---"
      while IFS= read -r line; do
        [[ "${line}" == "# --- end bundle:core ---" ]] && break
      done
    elif [[ "${line}" =~ include\(\$\{CMAKE_CURRENT_LIST_DIR\}/internal/(.+)\) ]]; then
      rel_path="${BASH_REMATCH[1]}"
      target_file="${SCRIPT_DIR}/cli/internal/${rel_path}"
      if [[ ! -f "${target_file}" ]]; then
        echo "Error: internal dependency missing at ${target_file}" >&2
        exit 1
      fi
      echo "# --- Begin: internal/${rel_path} ---"
      sed -E "s/^set\(CL_VERSION \"[^\"]*\"\)/set(CL_VERSION \"${VERSION}\")/" "${target_file}"
      echo ""
      echo "# --- End: internal/${rel_path} ---"
      echo ""
    else
      echo "${line}"
    fi
  done < "${ENTRY_FILE}"
}

{
  cat << 'HEADER'
#!/bin/sh
#[[ catalog: this file is both a shell script (these lines) and a CMake script (the rest).
cmake=${CMAKE:-cmake}
if ! command -v "$cmake" >/dev/null 2>&1; then
  echo "catalog: error: cmake not found (need CMake 3.25 or newer; set CMAKE=... to point to one)" >&2
  exit 127
fi
if [ -t 1 ]; then CATALOG_STDOUT_TTY=1; export CATALOG_STDOUT_TTY; fi
exec "$cmake" -P "$0" -- "$@"
]]
# ==============================================================================
# AUTOMATICALLY GENERATED FILE - DO NOT EDIT DIRECTLY
# Generated by Catalog's bundle-cli.sh
# ==============================================================================
HEADER
  bundle_cli
} > "${OUTPUT_FILE}"
chmod +x "${OUTPUT_FILE}"

echo "Successfully bundled the Catalog CLI (${VERSION}) into ${OUTPUT_FILE}"
